"""
Compare Drift-QL signal prevalence in *completed* trajectories between the
baseline (``default``) and the intervention (``refiner``), across datasets and
models, as a single heatmap.

Source of truth: the replay-detection records under
``analysis/analysis-results/pattern-resolution/{agent}-{model}-{dataset}.long.json``
(generated by ``run_analysis`` -> ``collect_pattern_resolution``, which replays
every trajectory through the live Drift-QL engine). Each record is one
``(instance, config)`` run carrying a ``signals`` map (name -> fired) plus a
``resolved`` label (``null`` when the trajectory never completed / was never
graded).

"Completed" = the trajectory produced a resolution label (``resolved`` is not
null); records with a missing label are dropped. Each heatmap cell is the
percentage of completed trajectories (for that dataset/model/config) in which
the (possibly collapsed) signal fired.

Signals are collapsed to the reportable families, matching the legacy figure:
  * Plan Violation  [B] -- any ``plan_compliance_*`` signal (blocking)
  * Oscillation     [B] -- ``oscillation`` OR ``thought_oscillation`` (blocking)
  * Long Stagnation [N] -- the four dwell signals, kept separate as
    Navigation / Reproduction / Patching / Validation (non-blocking)
  * Repeated Action [N] -- ``repeated_view`` (non-blocking)

Signals are excluded by request (so they never feed a collapsed family):
``plan_compliance_premature_validate``.

Layout (mirrors analysis/visualize/legacy): datasets are stacked vertically on
the left (bracketed); models run across the top, each spanning its two configs
(Vanilla / LivePlan) as adjacent columns.

Defaults:
  configs : ['default', 'refiner']
  datasets: ['swebench-pro', 'swebench']
  models  : ['deepseek-chat-v3-0324', 'gemini-2.5-flash', 'minimax-m2.5']
"""
import json
import argparse
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import matplotlib.pyplot as plt


# --------------------------------------------------------------------------- #
# Naming
# --------------------------------------------------------------------------- #

def load_name_maps():
    """Load display-name mappings from name_map.json (shared with the other plots)."""
    name_map_path = Path(__file__).parent / "name_map.json"
    with open(name_map_path) as f:
        maps = json.load(f)
    return maps['MODEL_NAME_MAP'], maps['DATASET_NAME_MAP'], maps['CONFIG_NAME_MAP']


MODEL_NAME_MAP, DATASET_NAME_MAP, CONFIG_NAME_MAP = load_name_maps()

DATASET_ABBR = {'swebench-pro': 'Pro', 'swebench': 'Verified'}

# Signals excluded by request: they never contribute to a collapsed family.
EXCLUDED_SIGNALS = {'plan_compliance_premature_validate'}

# Rows, in render order: (display label, row key, group). ``group`` controls the
# left-side bracketing; the four "stagnation" rows share the "[N] Long Stagnation"
# bracket. Row keys "plan_violation" / "oscillation" are collapsed families (see
# ``row_fired``); the rest are raw signal names.
ROW_SPEC: List[Tuple[str, str, str]] = [
    ("[B] Plan Violation",  "plan_violation",    "blocking"),
    ("[B] Oscillation",     "oscillation",       "blocking"),
    ("Navigation",          "dwell_L_navigate",  "stagnation"),
    ("Reproduction",        "dwell_L_reproduce", "stagnation"),
    ("Patching",            "dwell_P",           "stagnation"),
    ("Validation",          "dwell_V",           "stagnation"),
    ("[N] Repeated Action", "repeated_view",     "nonblocking"),
]


def row_fired(signals: Dict[str, bool], key: str) -> bool:
    """Did ``key`` fire for one trajectory, collapsing the two families?

    Plan Violation = any non-excluded ``plan_compliance_*`` signal.
    Oscillation    = ``oscillation`` or ``thought_oscillation``.
    Everything else is a raw signal lookup.
    """
    if key == "plan_violation":
        return any(v for k, v in signals.items()
                   if k.startswith("plan_compliance_") and k not in EXCLUDED_SIGNALS)
    if key == "oscillation":
        return bool(signals.get("oscillation")) or bool(signals.get("thought_oscillation"))
    return bool(signals.get(key))


# Behavioral-drift buckets: a trajectory is "in drift" for a bucket iff AT LEAST
# ONE of the bucket's row keys fires. ``Overall`` = any signal at all.
BLOCKING_KEYS = [k for _l, k, g in ROW_SPEC if g == "blocking"]
NONBLOCKING_KEYS = [k for _l, k, g in ROW_SPEC if g != "blocking"]
ALL_KEYS = [k for _l, k, _g in ROW_SPEC]
DRIFT_BUCKETS: List[Tuple[str, str, List[str]]] = [
    ("Overall",      "overall",     ALL_KEYS),
    ("Blocking",     "blocking",    BLOCKING_KEYS),
    ("Non-blocking", "nonblocking", NONBLOCKING_KEYS),
]


# --------------------------------------------------------------------------- #
# Data
# --------------------------------------------------------------------------- #

def long_json_path(pr_dir: Path, agent: str, model: str, dataset: str) -> Path:
    return pr_dir / f"{agent}-{model}-{dataset}.long.json"


def load_prevalence(path: Path, config: str) -> Optional[Dict[str, float]]:
    """Row firing rate (%) over *completed* trajectories for one config.

    Completed := ``resolved`` is not null. Returns ``{row_key: pct, '_n': count}``
    (counts over the completed subset), or ``None`` if the file is missing / has
    no completed rows for this config.
    """
    if not path.exists():
        return None

    records = json.loads(path.read_text(encoding="utf-8"))
    completed = [r for r in records
                 if r.get("config") == config and r.get("resolved") is not None]
    if not completed:
        return None

    n = len(completed)
    out: Dict[str, float] = {"_n": n}
    # Per-signal prevalence (%) for the heatmap cells.
    for _label, key, _group in ROW_SPEC:
        fired = sum(1 for r in completed if row_fired(r.get("signals", {}), key))
        out[key] = fired / n * 100.0
    # Per-bucket union COUNTS (# trajectories with >=1 signal in the bucket), so
    # the drift summary can pool across models exactly (fired / completed).
    for _name, tag, keys in DRIFT_BUCKETS:
        out[f"_fired_{tag}"] = float(sum(
            1 for r in completed
            if any(row_fired(r.get("signals", {}), k) for k in keys)))
    return out


def collect(pr_dir: Path, agent: str, datasets: List[str], models: List[str],
            configs: List[str]) -> Dict[Tuple[str, str, str], Dict[str, float]]:
    """Prevalence for every (dataset, model, config) that has completed data."""
    data: Dict[Tuple[str, str, str], Dict[str, float]] = {}
    for dataset in datasets:
        for model in models:
            path = long_json_path(pr_dir, agent, model, dataset)
            if not path.exists():
                print(f"Missing: {path}")
                continue
            for config in configs:
                prev = load_prevalence(path, config)
                if prev is not None:
                    data[(dataset, model, config)] = prev
    return data


# --------------------------------------------------------------------------- #
# Textual summary
# --------------------------------------------------------------------------- #

def print_drift_summary(data: Dict, datasets: List[str], models: List[str],
                        configs: List[str]) -> None:
    """Print behavioral-drift incidence per (dataset, config).

    A trajectory is "in drift" for a bucket iff AT LEAST ONE of the bucket's
    signals fires (Overall = any signal; Blocking / Non-blocking = any signal of
    that class). The reported number is the percentage of completed trajectories
    in drift, pooled over all models for that (dataset, config).
    """
    def bucket_pct(dataset: str, config: str, tag: str) -> Optional[float]:
        fired = total = 0.0
        for m in models:
            prev = data.get((dataset, m, config))
            if prev is None:
                continue
            fired += prev[f"_fired_{tag}"]
            total += prev["_n"]
        return 100.0 * fired / total if total else None

    def fmt(v: Optional[float]) -> str:
        return f"{'--':>12}" if v is None else f"{v:12.1f}"

    bucket_names = [name for name, _tag, _keys in DRIFT_BUCKETS]
    col_w = max(len("LivePlan"), *(len(CONFIG_NAME_MAP.get(c, c)) for c in configs))

    print("\nBehavioral-drift incidence (% of completed trajectories with >=1"
          " signal, pooled over models):")
    for dataset in datasets:
        if not any((dataset, m, c) in data for m in models for c in configs):
            continue
        print(f"\n  {DATASET_NAME_MAP.get(dataset, dataset)}")
        header = f"    {'Config':<{col_w}}  " + "  ".join(f"{b:>12}" for b in bucket_names)
        print(header)
        print("    " + "-" * (len(header) - 4))
        for config in configs:
            cells = [bucket_pct(dataset, config, tag) for _n, tag, _keys in DRIFT_BUCKETS]
            row = f"    {CONFIG_NAME_MAP.get(config, config):<{col_w}}  " + \
                  "  ".join(fmt(v) for v in cells)
            print(row)


