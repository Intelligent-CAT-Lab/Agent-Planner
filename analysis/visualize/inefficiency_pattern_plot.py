def generate_heatmap(data: Dict, datasets: List[str], models: List[str],
                     configs: List[str], output_path: Path, split_by_resolution: bool = False):
    """Generate heatmap visualization with datasets stacked vertically and models-configs as columns."""

    # Dataset abbreviations
    DATASET_ABBR = {
        'swebench-pro': 'Pro',
        'swebench': 'Verified'
    }

    # Define patterns (only individual patterns, no totals or any pattern)
    # Use complete names for better readability
    base_patterns = [
        ("[B] Plan Violation", "plan_violation", "blocking"),
        ("[B] Oscillation", "oscillation", "blocking"),
        ("Navigation", "dwell_L_navigate", "non-blocking"),
        ("Reproduce", "dwell_L_reproduce", "non-blocking"),
        ("Patch", "dwell_P", "non-blocking"),
        ("Validate", "dwell_V", "non-blocking"),
        ("[N] Repeated Action", "repeated_view", "non-blocking")
    ]

    # If split mode, duplicate each pattern for R and U
    if split_by_resolution:
        patterns = []
        for label, key, category in base_patterns:
            patterns.append(("R", label, key, category, "resolved"))
            patterns.append(("U", label, key, category, "unresolved"))
    else:
        patterns = [(label, label, key, category, None) for label, key, category in base_patterns]

    # Build model-config combinations (columns)
    model_config_tuples = []
    for model in models:
        for config in configs:
            model_config_tuples.append((model, config))

    n_patterns = len(patterns)
    n_datasets = len(datasets)
    n_rows = n_patterns * n_datasets
    n_cols = len(model_config_tuples)

    # Build data matrix (percentages): rows are dataset-pattern combinations
    matrix = np.zeros((n_rows, n_cols))
    row_labels = []

    for dataset_idx, dataset in enumerate(datasets):
        for pattern_idx, pattern_tuple in enumerate(patterns):
            if split_by_resolution:
                row_label, pattern_name, pattern_key, category, resolution_status = pattern_tuple
            else:
                row_label, pattern_name, pattern_key, category, _ = pattern_tuple
                resolution_status = None

            row_idx = dataset_idx * n_patterns + pattern_idx
            row_labels.append(row_label)

            # Fill data for this row
            for col_idx, (model, config) in enumerate(model_config_tuples):
                key = (dataset, model, config)
                if key in data:
                    if split_by_resolution:
                        # Get count for specific resolution status
                        count = data[key].get(f'{pattern_key}_{resolution_status}', 0)
                        # Total is resolved or unresolved count
                        total = data[key].get(f'{resolution_status}_count', 1)
                    else:
                        count = data[key].get(pattern_key, 0)
                        total = data[key].get('total_instances', 1)

                    pct = (count / total * 100) if total > 0 else 0
                    matrix[row_idx, col_idx] = pct

    # Create figure: adjust size based on split mode (taller cells for readability)
    fig_height = 22 if split_by_resolution else 13
    fig_width = 28  # Wider to accommodate labels and prevent model name overlap
    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    # Use green to red colormap
    cmap = plt.cm.RdYlGn_r  # Reversed: green=low, red=high

    # # Use green to red colormap with harmonious colors
    # import matplotlib.colors as mcolors
    # # Create a custom colormap with harmonious colors that allow readable black text
    # colors = ['#A1DE93', '#F7F48B', '#F47C7C']  # harmonious green -> yellow -> red
    # n_bins = 100
    # cmap = mcolors.LinearSegmentedColormap.from_list('custom', colors, N=n_bins)

    # Plot heatmap
    im = ax.imshow(matrix, cmap=cmap, aspect='auto', vmin=0, vmax=100)

    # Add colorbar without label to save space
    cbar = plt.colorbar(im, ax=ax, pad=0.02, fraction=0.02)
    cbar.ax.tick_params(labelsize=36)

    # Set ticks and labels
    ax.set_xticks(np.arange(n_cols))
    ax.set_yticks(np.arange(n_rows))

    # Column labels (config names)
    col_labels = [CONFIG_NAME_MAP.get(config, config) for _, config in model_config_tuples]
    ax.set_xticklabels(col_labels, fontsize=40, fontweight='bold', rotation=45, ha='right')

    # Hide default y-axis tick labels and tick marks
    ax.set_yticklabels([])
    ax.tick_params(axis='y', which='both', length=0)  # Remove tick marks

    # Manually add row labels very close to heatmap (closer than matplotlib default)
    for i, label in enumerate(row_labels):
        if label:  # Only add non-empty labels
            ax.text(-0.6, i, label, ha='right', va='center',
                   fontsize=36, fontweight='bold', transform=ax.transData, clip_on=False)

    # Add "[N] Long Stagnation" with bracket grouping for dwell patterns
    # Layout: Dataset brackets -> [N] Long Stagnation (with bracket) -> Pattern labels -> Heatmap
    for dataset_idx, dataset in enumerate(datasets):
        if split_by_resolution:
            # In split mode: dwell patterns are indices 2-5, each has 2 rows (R and U)
            dwell_start_row = dataset_idx * n_patterns + 2 * 2  # Start of Navigation R
            dwell_end_row = dataset_idx * n_patterns + 5 * 2 + 1  # End of Validate U
            dwell_mid_row = (dwell_start_row + dwell_end_row) / 2
        else:
            # In non-split mode: dwell patterns are indices 2-5 (Navigation, Reproduce, Patch, Validate)
            dwell_start_row = dataset_idx * n_patterns + 2  # Start of Navigation
            dwell_end_row = dataset_idx * n_patterns + 5  # End of Validate
            dwell_mid_row = (dwell_start_row + dwell_end_row) / 2

        # Draw bracket for [N] Long Stagnation grouping
        bracket_x = -1.8  # Position between dataset brackets and pattern labels
        bracket_width = 0.12

        # Vertical bar
        ax.plot([bracket_x, bracket_x], [dwell_start_row - 0.4, dwell_end_row + 0.4],
               color='black', linewidth=2.0, solid_capstyle='butt', clip_on=False)
        # Top cap
        ax.plot([bracket_x, bracket_x + bracket_width], [dwell_start_row - 0.4, dwell_start_row - 0.4],
               color='black', linewidth=2.0, solid_capstyle='butt', clip_on=False)
        # Bottom cap
        ax.plot([bracket_x, bracket_x + bracket_width], [dwell_end_row + 0.4, dwell_end_row + 0.4],
               color='black', linewidth=2.0, solid_capstyle='butt', clip_on=False)

        # Add two-line label: "[N] Long" on first line, "Stagnation" on second line
        # Position further left to avoid overlapping with pattern labels
        ax.text(bracket_x - 0.50, dwell_mid_row, "[N] Long\nStagnation", ha='center', va='center',
               fontsize=30, fontweight='bold', rotation=0, transform=ax.transData, clip_on=False,
               linespacing=0.9)

    # Add text annotations (cell values)
    for i in range(n_rows):
        for j in range(n_cols):
            value = matrix[i, j]
            ax.text(j, i, f'{value:.1f}', ha='center', va='center',
                   fontsize=38, fontweight='bold', color='black')

    # Add model headers (columns)
    model_groups = []
    current_model = None
    start_idx = 0

    for idx, (model, _) in enumerate(model_config_tuples):
        if model != current_model:
            if current_model is not None:
                model_groups.append((current_model, start_idx, idx))
            current_model = model
            start_idx = idx

    if current_model is not None:
        model_groups.append((current_model, start_idx, len(model_config_tuples)))

    for model, start, end in model_groups:
        model_name = MODEL_NAME_MAP.get(model, model)
        mid = (start + end - 1) / 2
        ax.text(mid, -0.9, model_name, ha='center', va='center',
               fontsize=38, fontweight='bold', style='italic', transform=ax.transData)

    # Add dataset labels on the left with brackets (leftmost position)
    for dataset_idx, dataset in enumerate(datasets):
        dataset_abbr = DATASET_ABBR.get(dataset, dataset)

        # Calculate the vertical span of this dataset
        start_row = dataset_idx * n_patterns - 0.5
        end_row = (dataset_idx + 1) * n_patterns - 0.5
        mid_row = dataset_idx * n_patterns + (n_patterns - 1) / 2

        # Create a bracket (move right to save space)
        bracket_x = -2.85  # Position for bracket
        bracket_width = 0.2

        # Simple bracket using lines (vertical bar with horizontal ticks)
        ax.plot([bracket_x, bracket_x], [start_row, end_row],
               color='black', linewidth=2.5, solid_capstyle='butt', clip_on=False)
        ax.plot([bracket_x, bracket_x + bracket_width], [start_row, start_row],
               color='black', linewidth=2.5, solid_capstyle='butt', clip_on=False)
        ax.plot([bracket_x, bracket_x + bracket_width], [end_row, end_row],
               color='black', linewidth=2.5, solid_capstyle='butt', clip_on=False)

        # Add dataset label next to the bracket (leftmost position, slightly closer)
        ax.text(bracket_x - 0.18, mid_row, dataset_abbr, ha='center', va='center',
               fontsize=40, fontweight='bold', rotation=90, transform=ax.transData, clip_on=False)

    # Draw vertical separators between models (subtle)
    for model, start, end in model_groups[:-1]:  # Exclude last
        ax.axvline(x=end - 0.5, color='gray', linewidth=1, linestyle='--', alpha=0.4)

    # Draw horizontal separators between datasets
    for dataset_idx in range(1, n_datasets):
        ax.axhline(y=dataset_idx * n_patterns - 0.5, color='black', linewidth=3, linestyle='-')

    # Draw horizontal separators between pattern groups within each dataset
    for dataset_idx in range(n_datasets):
        base = dataset_idx * n_patterns
        if split_by_resolution:
            # In split mode: 2 patterns per type, separate after blocking (4 rows) and non-blocking (4 rows)
            ax.axhline(y=base + 3.5, color='gray', linewidth=1.5, linestyle='--', alpha=0.6)
        else:
            # Non-split mode: 2 blocking, 2 non-blocking
            ax.axhline(y=base + 1.5, color='gray', linewidth=1.5, linestyle='--', alpha=0.6)

    # Styling - extend left limit to show dataset labels, brackets, and [N] Long Stagnation
    ax.set_xlim(-3.3, n_cols - 0.5)
    ax.set_ylim(n_rows - 0.5, -2.5)

    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['left'].set_visible(False)
    ax.spines['bottom'].set_visible(False)

    plt.tight_layout()

    # Save figure
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight', pad_inches=0.1)
    plt.close()

    print(f"Heatmap saved to: {output_path}")


def main():
    parser = argparse.ArgumentParser(description='Generate inefficiency pattern comparison tables')
    parser.add_argument('--agent', type=str, default='SWE-agent',
                       help='Agent name')
    parser.add_argument('--datasets', nargs='+', default=['swebench-pro', 'swebench'],
                       help='List of datasets')
    parser.add_argument('--models', nargs='+',
                       default=['deepseek-chat-v3-0324', 'gemini-2.5-flash', 'minimax-m2.5'],
                       help='List of models')
    parser.add_argument('--configs', nargs='+', default=['default', 'refiner'],
                       help='List of configs to compare')
    parser.add_argument('--split', action='store_true',
                       help='Split pattern prevalence by resolved (R) and unresolved (U)')

    args = parser.parse_args()

    # Determine project root
    script_dir = Path(__file__).parent.parent.parent
    comparison_dir = script_dir / "analysis" / "analysis-results" / "comparison"

    if not comparison_dir.exists():
        print(f"Comparison directory not found: {comparison_dir}")
        return

    # Collect data
    print("Collecting pattern data from CSV files...")
    print(f"Split by resolution: {args.split}")
    data = collect_all_data(comparison_dir, args.agent, args.datasets, args.models, args.configs, args.split)

    if not data:
        print("No data found. Check paths and configurations.")
        return

    print(f"Collected data for {len(data)} combinations")

    # Generate tables (skip if split mode)
    if not args.split:
        tables_dir = script_dir / "analysis" / "tables"
        tables_dir.mkdir(parents=True, exist_ok=True)

        latex_path = tables_dir / "inefficiency_patterns.tex"
        generate_latex_table(data, args.datasets, args.models, args.configs, latex_path)

        md_path = tables_dir / "inefficiency_patterns.md"
        generate_markdown_table(data, args.datasets, args.models, args.configs, md_path)

    # Generate heatmap
    figures_dir = script_dir / "analysis" / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)

    suffix = "_split" if args.split else ""
    heatmap_path = figures_dir / f"inefficiency_patterns_heatmap{suffix}.pdf"
    generate_heatmap(data, args.datasets, args.models, args.configs, heatmap_path, args.split)


if __name__ == "__main__":
    main()
