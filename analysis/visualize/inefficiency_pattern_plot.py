# Load name mappings
def load_name_maps():
    """Load name mappings from name_map.json."""
    import json
    name_map_path = Path(__file__).parent / "name_map.json"
    with open(name_map_path) as f:
        maps = json.load(f)
    return maps['MODEL_NAME_MAP'], maps['DATASET_NAME_MAP'], maps['CONFIG_NAME_MAP']


MODEL_NAME_MAP, DATASET_NAME_MAP, CONFIG_NAME_MAP = load_name_maps()


class CSVParser:
    """Smart CSV parser that dynamically detects column structure."""

    def __init__(self, csv_path: Path):
        self.csv_path = csv_path
        self.header_rows = []
        self.data_rows = []
        self.column_map = {}
        self._load_csv()
        self._detect_structure()

    def _load_csv(self):
        """Load CSV and separate headers from data."""
        with open(self.csv_path, 'r') as f:
            reader = csv.reader(f)
            rows = list(reader)

        # First 3 rows are headers
        self.header_rows = rows[:3]
        self.data_rows = rows[3:]

    def _detect_structure(self):
        """Detect which columns correspond to which configs."""
        header1 = self.header_rows[0]
        current_col = 1  # Skip Instance ID column

        config_sections = {}

        while current_col < len(header1):
            section_name = header1[current_col].strip()
            if not section_name:
                current_col += 1
                continue

            section_start = current_col

            # Determine section width based on config type
            if 'Vanilla Run' in section_name:
                section_width = 10
                config_sections['default'] = (section_start, section_start + section_width)
            elif 'Sage Run' in section_name:
                # Sage: no trigger status, 10 columns
                section_width = 10
                config_sections['sage'] = (section_start, section_start + section_width)
            elif 'Monitor Run' in section_name:
                section_width = 12
                config_sections['monitor'] = (section_start, section_start + section_width)
            elif 'Refiner-Only Run' in section_name:
                section_width = 12
                config_sections['refiner-only'] = (section_start, section_start + section_width)
            elif 'Live-Plan' in section_name or 'Refiner' in section_name:
                section_width = 12
                config_sections['refiner'] = (section_start, section_start + section_width)
            else:
                section_width = 1

            current_col = section_start + section_width

        self.column_map = config_sections

    def has_config(self, config: str) -> bool:
        """Check if a config section exists in the CSV."""
        return config in self.column_map

    def parse_config_patterns(self, row: List[str], config: str) -> Dict:
        """Parse pattern data from a row for the given config."""
        if config not in self.column_map:
            return None

        start, end = self.column_map[config]

        # For vanilla: patterns start at column 2-5
        # For planner configs: patterns start at column 4-7
        if config == 'default':
            if len(row) <= start + 5:
                return None
            patterns = {
                'plan_violation': row[start + 2] == '1' if len(row) > start + 2 else False,
                'oscillation': row[start + 3] == '1' if len(row) > start + 3 else False,
                'long_stagnation': row[start + 4] == '1' if len(row) > start + 4 else False,
                'repeated_view': row[start + 5] == '1' if len(row) > start + 5 else False
            }
        else:
            if len(row) <= start + 7:
                return None
            patterns = {
                'plan_violation': row[start + 4] == '1' if len(row) > start + 4 else False,
                'oscillation': row[start + 5] == '1' if len(row) > start + 5 else False,
                'long_stagnation': row[start + 6] == '1' if len(row) > start + 6 else False,
                'repeated_view': row[start + 7] == '1' if len(row) > start + 7 else False
            }

        return patterns


def count_patterns_from_csv(csv_path: Path, config: str) -> Dict:
    """Count pattern instances from CSV file."""
    if not csv_path.exists():
        return None

    parser = CSVParser(csv_path)

    if not parser.has_config(config):
        return None

    pattern_instances = defaultdict(set)
    all_with_pattern = set()
    total_instances = 0

    for row in parser.data_rows:
        if not row or not row[0]:
            continue

        instance_id = row[0]
        total_instances += 1

        patterns = parser.parse_config_patterns(row, config)
        if not patterns:
            continue

        for pattern_name, has_pattern in patterns.items():
            if has_pattern:
                pattern_instances[pattern_name].add(instance_id)
                all_with_pattern.add(instance_id)

    # Calculate totals
    blocking = pattern_instances['plan_violation'] | pattern_instances['oscillation']
    non_blocking = pattern_instances['long_stagnation'] | pattern_instances['repeated_view']

    return {
        'plan_violation': len(pattern_instances['plan_violation']),
        'oscillation': len(pattern_instances['oscillation']),
        'long_stagnation': len(pattern_instances['long_stagnation']),
        'repeated_view': len(pattern_instances['repeated_view']),
        'blocking_total': len(blocking),
        'non_blocking_total': len(non_blocking),
        'any_pattern': len(all_with_pattern),
        'total_instances': total_instances
    }


def collect_all_data(comparison_dir: Path, agent: str, datasets: List[str],
                     models: List[str], configs: List[str]) -> Dict:
    """Collect pattern data for all dataset-model-config combinations."""
    data = {}

    for dataset in datasets:
        for model in models:
            csv_path = comparison_dir / f"{agent}-{model}-{dataset}.csv"

            if not csv_path.exists():
                print(f"CSV not found: {csv_path}")
                continue

            for config in configs:
                pattern_counts = count_patterns_from_csv(csv_path, config)

                if pattern_counts:
                    key = (dataset, model, config)
                    data[key] = pattern_counts

    return data


def generate_latex_table(data: Dict, datasets: List[str], models: List[str],
                         configs: List[str], output_path: Path):
    """Generate LaTeX table with patterns as rows and datasets-models-configs as columns."""
    lines = []
    lines.append(r"\begin{table*}[h!]")
    lines.append(r"\centering")
    lines.append(r"\small")
    lines.append(r"\setlength{\tabcolsep}{2.5pt}")
    lines.append(r"\caption{Inefficiency patterns across datasets, models, and methods. "
                r"Percentages of instances with each pattern. "
                r"Blocking: plan violation, oscillation. "
                r"Non-blocking: long stagnation, repeated view.}")

    # Build dataset-model-config tuples
    dataset_model_config_tuples = []
    for dataset in datasets:
        for model in models:
            for config in configs:
                if (dataset, model, config) in data:
                    dataset_model_config_tuples.append((dataset, model, config))

    if not dataset_model_config_tuples:
        return

    n_cols = len(dataset_model_config_tuples)
    col_spec = "l|" + "r" * n_cols
    lines.append(f"\\begin{{tabular}}{{{col_spec}}}")
    lines.append(r"\toprule")

    # Header row 1: Dataset names with multicolumn
    header1 = r"\textbf{Pattern}"
    dataset_groups = []
    current_dataset = None
    start_idx = 0

    for idx, (dataset, _, _) in enumerate(dataset_model_config_tuples):
        if dataset != current_dataset:
            if current_dataset is not None:
                dataset_groups.append((current_dataset, start_idx, idx))
            current_dataset = dataset
            start_idx = idx

    if current_dataset is not None:
        dataset_groups.append((current_dataset, start_idx, len(dataset_model_config_tuples)))

    for dataset, start, end in dataset_groups:
        dataset_name = DATASET_NAME_MAP.get(dataset, dataset)
        span = end - start
        header1 += f" & \\multicolumn{{{span}}}{{c}}{{\\textbf{{{dataset_name}}}}}"

    lines.append(header1 + r" \\")

    # Header row 2: Model names with multicolumn (each model spans 2 configs)
    header2 = ""
    current_dataset = None
    current_model = None
    start_idx = 0

    model_groups = []
    for idx, (dataset, model, _) in enumerate(dataset_model_config_tuples):
        if dataset != current_dataset or model != current_model:
            if current_model is not None:
                model_groups.append((current_dataset, current_model, start_idx, idx))
            current_dataset = dataset
            current_model = model
            start_idx = idx

    if current_model is not None:
        model_groups.append((current_dataset, current_model, start_idx, len(dataset_model_config_tuples)))

    for dataset, model, start, end in model_groups:
        model_name = MODEL_NAME_MAP.get(model, model)
        span = end - start
        if span > 1:
            header2 += f" & \\multicolumn{{{span}}}{{c}}{{\\textit{{{model_name}}}}}"
        else:
            header2 += f" & \\textit{{{model_name}}}"

    lines.append(header2 + r" \\")

    # Header row 3: Config names
    subheader_parts = [""]
    for _, _, config in dataset_model_config_tuples:
        config_name = CONFIG_NAME_MAP.get(config, config)
        subheader_parts.append(f"\\scriptsize {config_name}")
    lines.append(" & ".join(subheader_parts) + r" \\")
    lines.append(r"\midrule")

    # Pattern rows
    patterns = [
        (r"\textbf{Blocking}", None, False),
        (r"$\quad$ Plan Violation", "plan_violation", False),
        (r"$\quad$ Oscillation", "oscillation", False),
        (r"$\quad$ \textit{Total}", "blocking_total", True),
        (r"\textbf{Non-blocking}", None, False),
        (r"$\quad$ Long Stagnation", "long_stagnation", False),
        (r"$\quad$ Repeated Action", "repeated_view", False),
        (r"$\quad$ \textit{Total}", "non_blocking_total", True),
        (r"\textbf{Any Pattern}", "any_pattern", False)
    ]

    for pattern_label, pattern_key, add_line in patterns:
        row_parts = [pattern_label]

        # Add counts for each dataset-model-config tuple
        for dataset, model, config in dataset_model_config_tuples:
            key = (dataset, model, config)
            if pattern_key is None:
                # Category header row, no data
                row_parts.append("")
            elif key in data:
                count = data[key].get(pattern_key, 0)
                total = data[key].get('total_instances', 1)
                pct = (count / total * 100) if total > 0 else 0
                row_parts.append(f"{pct:.1f}\\%")
            else:
                row_parts.append(r"---")

        lines.append(" & ".join(row_parts) + r" \\")

        # Add line after totals
        if add_line:
            lines.append(r"\cmidrule{1-" + str(n_cols + 1) + "}")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\label{tab:inefficiency_patterns}")
    lines.append(r"\end{table*}")

    # Write to file
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))

    print(f"LaTeX table saved to: {output_path}")


def generate_markdown_table(data: Dict, datasets: List[str], models: List[str],
                            configs: List[str], output_path: Path):
    """Generate Markdown table with patterns as rows and datasets-models-configs as columns."""
    lines = []
    lines.append("# Inefficiency Pattern Analysis\n")

    # Build dataset-model-config tuples
    dataset_model_config_tuples = []
    for dataset in datasets:
        for model in models:
            for config in configs:
                if (dataset, model, config) in data:
                    dataset_model_config_tuples.append((dataset, model, config))

    if not dataset_model_config_tuples:
        return

    # Header with three-level grouping
    header_parts = ["Pattern"]
    for dataset, model, config in dataset_model_config_tuples:
        dataset_name = DATASET_NAME_MAP.get(dataset, dataset)
        model_name = MODEL_NAME_MAP.get(model, model)
        config_name = CONFIG_NAME_MAP.get(config, config)
        header_parts.append(f"{dataset_name}<br>{model_name}<br>{config_name}")

    header = "| " + " | ".join(header_parts) + " |"
    separator = "|" + "|".join([":-------" if i == 0 else "-------:" for i in range(len(header_parts))]) + "|"

    lines.append(header)
    lines.append(separator)

    # Pattern rows
    patterns = [
        ("**Blocking**", None),
        ("&nbsp;&nbsp;Plan Violation", "plan_violation"),
        ("&nbsp;&nbsp;Oscillation", "oscillation"),
        ("&nbsp;&nbsp;*Total*", "blocking_total"),
        ("**Non-blocking**", None),
        ("&nbsp;&nbsp;Long Stagnation", "long_stagnation"),
        ("&nbsp;&nbsp;Repeated Action", "repeated_view"),
        ("&nbsp;&nbsp;*Total*", "non_blocking_total"),
        ("**Any Pattern**", "any_pattern")
    ]

    for pattern_label, pattern_key in patterns:
        row_parts = [pattern_label]

        # Add counts for each dataset-model-config tuple
        for dataset, model, config in dataset_model_config_tuples:
            key = (dataset, model, config)
            if pattern_key is None:
                # Category header row, no data
                row_parts.append("")
            elif key in data:
                count = data[key].get(pattern_key, 0)
                total = data[key].get('total_instances', 1)
                pct = (count / total * 100) if total > 0 else 0
                row_parts.append(f"{count} ({pct:.1f}%)")
            else:
                row_parts.append("--")

        lines.append("| " + " | ".join(row_parts) + " |")

    # Write to file
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))

    print(f"Markdown table saved to: {output_path}")


def generate_heatmap(data: Dict, datasets: List[str], models: List[str],
                     configs: List[str], output_path: Path):
    """Generate heatmap visualization with datasets stacked vertically and models-configs as columns."""

    # Define patterns (excluding category headers)
    patterns = [
        ("Plan Violation", "plan_violation", "blocking"),
        ("Oscillation", "oscillation", "blocking"),
        ("Total", "blocking_total", "blocking"),
        ("Long Stagnation", "long_stagnation", "non-blocking"),
        ("Repeated Action", "repeated_view", "non-blocking"),
        ("Total", "non_blocking_total", "non-blocking"),
        ("Any Pattern", "any_pattern", "any")
    ]

    # Build model-config combinations (columns)
    model_config_tuples = []
    for model in models:
        for config in configs:
            model_config_tuples.append((model, config))

    n_patterns = len(patterns)
    n_datasets = len(datasets)
    n_rows = n_patterns * n_datasets
    n_cols = len(model_config_tuples)

    # Build data matrix (percentages): rows are dataset-pattern combinations
    matrix = np.zeros((n_rows, n_cols))
    row_labels = []

    for dataset_idx, dataset in enumerate(datasets):
        for pattern_idx, (pattern_label, pattern_key, category) in enumerate(patterns):
            row_idx = dataset_idx * n_patterns + pattern_idx

            # Build row label
            if category == "blocking":
                marker = "[B] "
            elif category == "non-blocking":
                marker = "[N] "
            else:
                marker = ""
            row_labels.append(f"{marker}{pattern_label}")

            # Fill data for this row
            for col_idx, (model, config) in enumerate(model_config_tuples):
                key = (dataset, model, config)
                if key in data:
                    count = data[key].get(pattern_key, 0)
                    total = data[key].get('total_instances', 1)
                    pct = (count / total * 100) if total > 0 else 0
                    matrix[row_idx, col_idx] = pct

    # Create figure: wider and taller to avoid overlap
    fig, ax = plt.subplots(figsize=(24, 15))
    # Use green to red colormap
    cmap = plt.cm.RdYlGn_r  # Reversed: green=low, red=high

    # # Use green to red colormap with harmonious colors
    # import matplotlib.colors as mcolors
    # # Create a custom colormap with harmonious colors that allow readable black text
    # colors = ['#A1DE93', '#F7F48B', '#F47C7C']  # harmonious green -> yellow -> red
    # n_bins = 100
    # cmap = mcolors.LinearSegmentedColormap.from_list('custom', colors, N=n_bins)

    # Plot heatmap
    im = ax.imshow(matrix, cmap=cmap, aspect='auto', vmin=0, vmax=100)

    # Add colorbar
    cbar = plt.colorbar(im, ax=ax, pad=0.02, fraction=0.02)
    cbar.set_label('Percentage (%)', fontsize=34, fontweight='bold')
    cbar.ax.tick_params(labelsize=32)

    # Set ticks and labels
    ax.set_xticks(np.arange(n_cols))
    ax.set_yticks(np.arange(n_rows))

    # Column labels (config names)
    col_labels = [CONFIG_NAME_MAP.get(config, config) for _, config in model_config_tuples]
    ax.set_xticklabels(col_labels, fontsize=34, rotation=45, ha='right')

    # Row labels
    ax.set_yticklabels(row_labels, fontsize=32, fontweight='bold')

    # Add text annotations
    for i in range(n_rows):
        for j in range(n_cols):
            value = matrix[i, j]
            ax.text(j, i, f'{value:.1f}', ha='center', va='center',
                   fontsize=34, fontweight='bold', color='black')

    # Add model headers (columns)
    model_groups = []
    current_model = None
    start_idx = 0

    for idx, (model, _) in enumerate(model_config_tuples):
        if model != current_model:
            if current_model is not None:
                model_groups.append((current_model, start_idx, idx))
            current_model = model
            start_idx = idx

    if current_model is not None:
        model_groups.append((current_model, start_idx, len(model_config_tuples)))

    for model, start, end in model_groups:
        model_name = MODEL_NAME_MAP.get(model, model)
        mid = (start + end - 1) / 2
        ax.text(mid, -0.9, model_name, ha='center', va='center',
               fontsize=34, fontweight='bold', style='italic', transform=ax.transData)

    # Add dataset labels on the right (vertical orientation)
    for dataset_idx, dataset in enumerate(datasets):
        dataset_name = DATASET_NAME_MAP.get(dataset, dataset)
        mid_row = dataset_idx * n_patterns + (n_patterns - 1) / 2
        ax.text(n_cols + 0.6, mid_row, dataset_name, ha='center', va='center',
               fontsize=36, fontweight='bold', rotation=90, transform=ax.transData)

    # Draw vertical separators between models (subtle)
    for model, start, end in model_groups[:-1]:  # Exclude last
        ax.axvline(x=end - 0.5, color='gray', linewidth=1, linestyle='--', alpha=0.4)

    # Draw horizontal separators between datasets
    for dataset_idx in range(1, n_datasets):
        ax.axhline(y=dataset_idx * n_patterns - 0.5, color='black', linewidth=3, linestyle='-')

    # Draw horizontal separators between pattern groups within each dataset
    for dataset_idx in range(n_datasets):
        base = dataset_idx * n_patterns
        ax.axhline(y=base + 2.5, color='gray', linewidth=1.5, linestyle='--', alpha=0.6)
        ax.axhline(y=base + 5.5, color='gray', linewidth=1.5, linestyle='--', alpha=0.6)

    # Styling
    ax.set_xlim(-0.5, n_cols - 0.5)
    ax.set_ylim(n_rows - 0.5, -1.5)

    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['left'].set_visible(False)
    ax.spines['bottom'].set_visible(False)

    plt.tight_layout()

    # Save figure
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight', pad_inches=0.1)
    plt.close()

    print(f"Heatmap saved to: {output_path}")


def main():
    parser = argparse.ArgumentParser(description='Generate inefficiency pattern comparison tables')
    parser.add_argument('--agent', type=str, default='SWE-agent',
                       help='Agent name')
    parser.add_argument('--datasets', nargs='+', default=['swebench-pro', 'swebench'],
                       help='List of datasets')
    parser.add_argument('--models', nargs='+',
                       default=['deepseek-chat-v3-0324', 'gemini-2.5-flash', 'minimax-m2.5'],
                       help='List of models')
    parser.add_argument('--configs', nargs='+', default=['default', 'refiner'],
                       help='List of configs to compare')

    args = parser.parse_args()

    # Determine project root
    script_dir = Path(__file__).parent.parent.parent
    comparison_dir = script_dir / "analysis" / "analysis-results" / "comparison"

    if not comparison_dir.exists():
        print(f"Comparison directory not found: {comparison_dir}")
        return

    # Collect data
    print("Collecting pattern data from CSV files...")
    data = collect_all_data(comparison_dir, args.agent, args.datasets, args.models, args.configs)

    if not data:
        print("No data found. Check paths and configurations.")
        return

    print(f"Collected data for {len(data)} combinations")

    # Generate tables
    tables_dir = script_dir / "analysis" / "tables"
    tables_dir.mkdir(parents=True, exist_ok=True)

    latex_path = tables_dir / "inefficiency_patterns.tex"
    generate_latex_table(data, args.datasets, args.models, args.configs, latex_path)

    md_path = tables_dir / "inefficiency_patterns.md"
    generate_markdown_table(data, args.datasets, args.models, args.configs, md_path)

    # Generate heatmap
    figures_dir = script_dir / "analysis" / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)

    heatmap_path = figures_dir / "inefficiency_patterns_heatmap.pdf"
    generate_heatmap(data, args.datasets, args.models, args.configs, heatmap_path)


if __name__ == "__main__":
    main()
