"""
Compare the number of patterns (break down by blocking: plan_violation, oscillation; non-blocking: long_stagnation, repeated view) between the configs (default to ['default', 'refiner']) for each dataset-model pair.
Read the data from analysis/analysis-results/comparison/{agent}-{model}-{dataset}.csv. (which is generated by run_analysis.py; smartly parse the csv to load the data (you can refer to analysis_pattern_resolution.py for how to parse the csv))
List the number of instances contain such pattern (and the number of instances exist any of the patterns) and generate table (latex, md) under analysis/tables/.
default configs list: ['default', 'refiner']
default dataset list: ['swebench', 'swebench-pro']
default model list: ['deepseek-chat-v3-0324', 'gemini-2.5-flash', 'minimax-m2.5']

"""
