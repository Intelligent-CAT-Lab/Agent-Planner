def _contiguous_groups(items: List) -> List[Tuple[object, int, int]]:
    """[(value, start, end)] for runs of equal consecutive values (end exclusive)."""
    groups: List[Tuple[object, int, int]] = []
    start = 0
    for i in range(1, len(items) + 1):
        if i == len(items) or items[i] != items[start]:
            groups.append((items[start], start, i))
            start = i
    return groups


def generate_heatmap(data: Dict, datasets: List[str], models: List[str],
                     configs: List[str], output_path: Path) -> None:
    # Keep only datasets/models that actually have data (preserve requested order).
    datasets = [d for d in datasets
                if any((d, m, c) in data for m in models for c in configs)]
    models = [m for m in models
              if any((d, m, c) in data for d in datasets for c in configs)]
    if not datasets or not models:
        print("No data to plot.")
        return

    # Columns: model -> config (Vanilla / LivePlan adjacent per model).
    columns = [(m, c) for m in models for c in configs]
    n_patterns = len(ROW_SPEC)
    n_rows = n_patterns * len(datasets)
    n_cols = len(columns)

    # Matrix: rows stacked per dataset block; NaN where a cell is missing.
    matrix = np.full((n_rows, n_cols), np.nan)
    for di, dataset in enumerate(datasets):
        for pi, (_label, key, _group) in enumerate(ROW_SPEC):
            r = di * n_patterns + pi
            for cj, (model, config) in enumerate(columns):
                prev = data.get((dataset, model, config))
                if prev is not None:
                    matrix[r, cj] = prev.get(key, np.nan)

    # --- Font sizes (one knob per element; compact figure, large text) ------ #
    FS_CELL, FS_ROW, FS_MODEL = 26, 25, 28
    FS_CONFIG, FS_DATASET, FS_STAG, FS_CBAR = 25, 29, 22, 22

    fig_w = 2.35 * n_cols + 3.0
    fig_h = 0.70 * n_rows + 1.2
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))

    cmap = plt.cm.RdYlGn_r  # green = low prevalence, red = high
    cmap.set_bad(color="#dddddd")  # missing cells
    im = ax.imshow(matrix, cmap=cmap, aspect="auto", vmin=0, vmax=100)

    cbar = plt.colorbar(im, ax=ax, pad=0.015, fraction=0.030)
    cbar.ax.tick_params(labelsize=FS_CBAR)

    # Cell annotations.
    for i in range(n_rows):
        for j in range(n_cols):
            v = matrix[i, j]
            txt = "--" if not np.isfinite(v) else f"{v:.1f}"
            ax.text(j, i, txt, ha="center", va="center",
                    fontsize=FS_CELL, fontweight="bold", color="black")

    # Hide native axis furniture; we place everything manually.
    ax.set_xticks([])
    ax.set_yticks([])
    for spine in ax.spines.values():
        spine.set_visible(False)

    # --- Left-margin furniture, packed by MEASURED text width --------------- #
    # Columns, right -> left: row labels | [N] Long Stagnation bracket + label |
    # dataset bracket + abbr. Each piece is placed just left of the previous one
    # using real rendered extents, so nothing overlaps and the gaps stay uniform
    # and tight regardless of font size or figure dimensions.
    GAP, CAP = 0.16, 0.12
    row_label_x = -0.45

    ax.set_ylim(n_rows - 0.5, -1.7)
    ax.set_xlim(-6.0, n_cols - 0.5)   # provisional; tightened once furniture is placed
    plt.tight_layout()                # size the axes large BEFORE measuring text widths
    fig.canvas.draw()
    rend = fig.canvas.get_renderer()
    inv = ax.transData.inverted()

    def edges(t):
        """(left, right, width) of a text's rendered bbox, in data-x units."""
        bb = t.get_window_extent(rend)
        lo, hi = inv.transform((bb.x0, 0))[0], inv.transform((bb.x1, 0))[0]
        return lo, hi, hi - lo

    # 1) Row labels.
    row_texts = []
    for di in range(len(datasets)):
        for pi, (label, _key, _group) in enumerate(ROW_SPEC):
            r = di * n_patterns + pi
            row_texts.append(ax.text(row_label_x, r, label, ha="right", va="center",
                                     fontsize=FS_ROW, fontweight="bold", clip_on=False))
    fig.canvas.draw()

    # 2) "[N] Long Stagnation" bracket, just left of the widest dwell label.
    dwell_pis = [pi for pi, (_l, _k, g) in enumerate(ROW_SPEC) if g == "stagnation"]
    dwell_texts = [row_texts[di * n_patterns + pi]
                   for di in range(len(datasets)) for pi in dwell_pis]
    stag_x = min(edges(t)[0] for t in dwell_texts) - GAP
    stag_labels = []
    for di in range(len(datasets)):
        rows = [di * n_patterns + pi for pi in dwell_pis]
        top, bot = min(rows) - 0.42, max(rows) + 0.42
        ax.plot([stag_x, stag_x], [top, bot], color="black", lw=2.0, clip_on=False)
        for y in (top, bot):
            ax.plot([stag_x, stag_x + CAP], [y, y], color="black", lw=2.0, clip_on=False)
        stag_labels.append(ax.text(stag_x - GAP, (top + bot) / 2.0, "[N] Long\nStagnation",
                                   ha="right", va="center", fontsize=FS_STAG,
                                   fontweight="bold", linespacing=0.9, clip_on=False))
    fig.canvas.draw()

    # 3) Dataset bracket + rotated abbreviation, just left of the stag label.
    data_x = min(edges(t)[0] for t in stag_labels) - GAP
    probe = ax.text(data_x - 2.0, 0, DATASET_ABBR.get(datasets[0], datasets[0]),
                    rotation=90, ha="center", va="center", fontsize=FS_DATASET,
                    fontweight="bold")
    fig.canvas.draw()
    abbr_w = edges(probe)[2]
    probe.remove()
    abbr_cx = data_x - GAP - abbr_w / 2.0
    for di, dataset in enumerate(datasets):
        top = di * n_patterns - 0.5
        bot = (di + 1) * n_patterns - 0.5
        mid = di * n_patterns + (n_patterns - 1) / 2.0
        ax.plot([data_x, data_x], [top, bot], color="black", lw=2.4, clip_on=False)
        for y in (top, bot):
            ax.plot([data_x, data_x + CAP], [y, y], color="black", lw=2.4, clip_on=False)
        ax.text(abbr_cx, mid, DATASET_ABBR.get(dataset, dataset), ha="center",
                va="center", rotation=90, fontsize=FS_DATASET, fontweight="bold",
                clip_on=False)

    # Tighten to the final x-range now, so model-name widths are measured at the
    # scale they will actually render at.
    left_lim = abbr_cx - abbr_w / 2.0 - 0.12
    ax.set_xlim(left_lim, n_cols - 0.5)
    fig.canvas.draw()

    # --- Model headers (top): auto-fit so no name overflows its 2-col span --- #
    def text_w(s, fs):
        t = ax.text(0, -0.85, s, fontsize=fs, fontweight="bold", style="italic")
        fig.canvas.draw()
        w = edges(t)[2]
        t.remove()
        return w

    mgroups = _contiguous_groups([m for m, _c in columns])
    fs_model = FS_MODEL
    for model, start, end in mgroups:
        span = (end - start) - 0.14   # leave a hair of padding inside the span
        w = text_w(MODEL_NAME_MAP.get(model, model), fs_model)
        if w > span:
            fs_model = max(11.0, fs_model * span / w)

    for model, start, end in mgroups:
        mid = (start + end - 1) / 2.0
        ax.text(mid, -0.85, MODEL_NAME_MAP.get(model, model), ha="center",
                va="center", fontsize=fs_model, fontweight="bold", style="italic",
                clip_on=False)
        if end < n_cols:
            ax.axvline(end - 0.5, color="gray", lw=1.2, ls="--", alpha=0.5)

    for cj, (_model, config) in enumerate(columns):
        ax.text(cj, n_rows - 0.4, CONFIG_NAME_MAP.get(config, config), ha="center",
                va="top", fontsize=FS_CONFIG, fontweight="bold", rotation=40,
                clip_on=False)

    # --- Separators between dataset blocks and after the blocking rows ------ #
    for di in range(1, len(datasets)):
        ax.axhline(di * n_patterns - 0.5, color="black", lw=2.5)
    n_blocking = sum(1 for _l, _k, g in ROW_SPEC if g == "blocking")
    for di in range(len(datasets)):
        ax.axhline(di * n_patterns + n_blocking - 0.5, color="gray", lw=1.2,
                   ls="--", alpha=0.6)

    # xlim/ylim are already final (set above, before the auto-fit measurements);
    # bbox_inches="tight" crops the surrounding whitespace at save time.
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches="tight", pad_inches=0.08)
    plt.close()
    print(f"Heatmap saved to: {output_path}")


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #

def main():
    ap = argparse.ArgumentParser(description="Drift-QL signal heatmap (default vs refiner)")
    ap.add_argument('--agent', default='SWE-agent')
    ap.add_argument('--datasets', nargs='+', default=['swebench-pro', 'swebench'])
    ap.add_argument('--models', nargs='+',
                    default=['deepseek-chat-v3-0324', 'gemini-2.5-flash', 'minimax-m2.5'])
    ap.add_argument('--configs', nargs='+', default=['default', 'refiner'])
    ap.add_argument('--output', default=None, help='Output path (default: analysis/figures/...)')
    args = ap.parse_args()

    repo = Path(__file__).resolve().parent.parent.parent
    pr_dir = repo / "analysis" / "analysis-results" / "pattern-resolution"
    if not pr_dir.exists():
        print(f"pattern-resolution directory not found: {pr_dir}")
        return

    print("Collecting signal prevalence from pattern-resolution long.json ...")
    data = collect(pr_dir, args.agent, args.datasets, args.models, args.configs)
    if not data:
        print("No data found. Check paths and configurations.")
        return
    print(f"Collected {len(data)} (dataset, model, config) combinations")

    print_drift_summary(data, args.datasets, args.models, args.configs)

    out = Path(args.output) if args.output else \
        repo / "analysis" / "figures" / "inefficiency_patterns_heatmap.pdf"
    generate_heatmap(data, args.datasets, args.models, args.configs, out)


if __name__ == "__main__":
    main()
